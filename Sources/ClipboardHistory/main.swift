import AppKit
import SwiftUI
import Carbon
import ApplicationServices

struct Clip: Identifiable, Codable {
    var id = UUID()
    let date: Date
    let text: String?
    let image: Data?
    var title: String { text ?? "Imagem" }
}

@MainActor
final class History: ObservableObject {
    @Published var items: [Clip] = []
    @Published var paused = false
    private var changeCount: Int
    private var timer: Timer?
    private let file: URL
    private let limit = 100

    init() {
        let folder = URL.applicationSupportDirectory.appending(path: "ClipboardHistory", directoryHint: .isDirectory)
        file = folder.appending(path: "history.json")
        changeCount = NSPasteboard.general.changeCount
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: file), let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            items = Array(saved.prefix(limit))
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        guard !paused else { return }
        // Password managers commonly mark sensitive or transient clipboard contents.
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !excluded.contains(where: { board.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        let clip: Clip
        if let image = NSImage(pasteboard: board),
           let tiff = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiff),
           let png = bitmap.representation(using: .png, properties: [:]), png.count <= 10_000_000 {
            clip = Clip(date: Date(), text: nil, image: png)
        } else if let text = board.string(forType: .string), !text.isEmpty, text.utf8.count <= 1_000_000 {
            clip = Clip(date: Date(), text: text, image: nil)
        } else { return }
        items.removeAll { $0.text == clip.text && $0.image == clip.image }
        items.insert(clip, at: 0)
        items = Array(items.prefix(limit))
        save()
    }

    func copy(_ item: Clip) {
        let board = NSPasteboard.general
        board.clearContents()
        if let text = item.text { board.setString(text, forType: .string) }
        else if let data = item.image, let image = NSImage(data: data) {
            // Offer the native image representations as well as PNG to receiving apps.
            board.writeObjects([image])
            board.setData(data, forType: .png)
        }
        changeCount = board.changeCount
    }
    func remove(_ item: Clip) { items.removeAll { $0.id == item.id }; save() }
    func clear() { items.removeAll(); save() }
    private func save() {
        do {
            let data = try JSONEncoder().encode(items)
            try data.write(to: file, options: [.atomic])
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        } catch { NSLog("Não foi possível salvar o histórico: %@", error.localizedDescription) }
    }
}

struct HistoryView: View {
    @ObservedObject var history: History
    @ObservedObject var settings: LaunchSettings
    let close: () -> Void
    let detach: () -> Void
    let select: (Clip) -> Void
    @State private var showSettings = false
    @State private var search = ""
    @State private var confirmClear = false
    @FocusState private var searching: Bool
    var filtered: [Clip] {
        history.items.filter { search.isEmpty || $0.title.localizedCaseInsensitiveContains(search) }
    }
    var body: some View {
        VStack(spacing: 12) {
            HStack {
                Image(systemName: "clipboard.fill").foregroundStyle(.tint)
                Text("Histórico de Clipboard").font(.headline)
                Spacer()
                Button { NSApp.terminate(nil) } label: { Image(systemName: "power") }
                    .buttonStyle(.borderless).help("Sair do ClipboardHistory").accessibilityLabel("Sair do ClipboardHistory")
                Button { showSettings = true } label: { Image(systemName: "gearshape") }
                    .buttonStyle(.borderless).help("Ajustes")
                Button(action: detach) { Image(systemName: "arrow.up.left.and.arrow.down.right") }
                    .buttonStyle(.borderless).help("Abrir como janela flutuante para arrastar")
                Text("⌃⌘V").foregroundStyle(.secondary)
            }
            TextField("Buscar textos…", text: $search)
                .textFieldStyle(.roundedBorder).focused($searching)
                .onSubmit { if let first = filtered.first { select(first) } }
            if filtered.isEmpty {
                ContentUnavailableView(search.isEmpty ? "Seu histórico está vazio" : "Nenhum resultado", systemImage: "clipboard", description: Text("Copie textos ou imagens para vê-los aqui."))
            } else {
                ScrollView {
                    LazyVStack(spacing: 8) {
                        ForEach(filtered) { item in
                            HStack(alignment: .top) {
                                Button {
                                    select(item)
                                } label: {
                                    HStack(alignment: .top, spacing: 10) {
                                        if let data = item.image, let image = NSImage(data: data) {
                                            Image(nsImage: image).resizable().scaledToFit().frame(width: 80, height: 60)
                                        } else { Image(systemName: "text.alignleft").foregroundStyle(.secondary) }
                                        VStack(alignment: .leading, spacing: 5) {
                                            Text(item.title).lineLimit(3).frame(maxWidth: .infinity, alignment: .leading)
                                            Text(item.date, format: .dateTime.day().month().hour().minute()).font(.caption).foregroundStyle(.secondary)
                                        }
                                    }.padding(10).contentShape(Rectangle())
                                }.buttonStyle(.plain)
                                Button { history.remove(item) } label: { Image(systemName: "xmark") }
                                    .buttonStyle(.borderless).help("Excluir item").padding(10)
                            }.background(.quaternary.opacity(0.5), in: RoundedRectangle(cornerRadius: 8))
                        }
                    }
                }
            }
            Divider()
            HStack {
                Text("\(history.items.count)/100").font(.caption).foregroundStyle(.secondary)
                Toggle("Pausar", isOn: $history.paused).toggleStyle(.checkbox)
                Spacer()
                Button("Limpar") { confirmClear = true }.disabled(history.items.isEmpty)
                Button("Fechar", action: close).help("Fechar a janela e manter o app em execução")
            }
            Text("Selecione para colar no app anterior").font(.caption).foregroundStyle(.secondary)
        }
        .padding(16).frame(width: 440, height: 550)
        .sheet(isPresented: $showSettings) { SettingsView(settings: settings) }
        .onAppear { searching = true }
        .onExitCommand(perform: close)
        .confirmationDialog("Apagar todo o histórico salvo?", isPresented: $confirmClear) {
            Button("Apagar histórico", role: .destructive) { history.clear() }
        }
    }
}

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate, NSPopoverDelegate {
    private var status: NSStatusItem!
    private let popover = NSPopover()
    private var floatingWindow: NSPanel?
    private let history = History()
    private let settings = LaunchSettings()
    private var hotkey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var destination: NSRunningApplication?
    private var activationObserver: NSObjectProtocol?
    private var pasteTask: Task<Void, Never>?

    func applicationDidFinishLaunching(_ notification: Notification) {
        NSApp.setActivationPolicy(.accessory)
        rememberDestination(NSWorkspace.shared.frontmostApplication)
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.rememberDestination(NSWorkspace.shared.frontmostApplication)
            }
        }
        status = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        status.button?.image = NSImage(systemSymbolName: "clipboard", accessibilityDescription: "Histórico de Clipboard")
        status.button?.target = self
        status.button?.action = #selector(toggle)
        popover.behavior = .transient
        popover.delegate = self
        popover.contentViewController = makeContent()
        var event = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, context in
            guard let context else { return OSStatus(eventNotHandledErr) }
            MainActor.assumeIsolated {
                Unmanaged<AppDelegate>.fromOpaque(context).takeUnretainedValue().toggle()
            }
            return noErr
        }, 1, &event, Unmanaged.passUnretained(self).toOpaque(), &handler)
        let result = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(controlKey | cmdKey), EventHotKeyID(signature: 0x434C4950, id: 1), GetApplicationEventTarget(), 0, &hotkey)
        if result != noErr {
            let alert = NSAlert()
            alert.messageText = "Atalho indisponível"
            alert.informativeText = "Não foi possível registrar Control + Command + V. Abra o histórico pelo ícone na barra de menus."
            alert.runModal()
        }
    }
    private func makeContent() -> NSViewController {
        NSHostingController(rootView: HistoryView(history: history, settings: settings, close: { [weak self] in
            self?.popover.performClose(nil)
            self?.floatingWindow?.orderOut(nil)
        }, detach: { [weak self] in self?.detach() }, select: { [weak self] item in
            self?.paste(item)
        }))
    }

    private func rememberDestination(_ app: NSRunningApplication?) {
        guard let app, app.processIdentifier != ProcessInfo.processInfo.processIdentifier,
              app.activationPolicy == .regular else { return }
        destination = app
    }

    private func paste(_ item: Clip) {
        pasteTask?.cancel()
        history.copy(item)
        popover.performClose(nil)
        floatingWindow?.orderOut(nil)
        guard let target = destination, !target.isTerminated else { return }
        guard AXIsProcessTrusted() else {
            let alert = NSAlert()
            alert.messageText = "Permita a colagem automática"
            alert.informativeText = "O item já foi copiado. Para colar ao clicar, habilite ClipboardHistory em Ajustes do Sistema → Privacidade e Segurança → Acessibilidade. Sem essa permissão, volte ao app e use Command + V."
            alert.addButton(withTitle: "Abrir Ajustes")
            alert.addButton(withTitle: "Agora não")
            if alert.runModal() == .alertFirstButtonReturn,
               let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
                NSWorkspace.shared.open(url)
            }
            return
        }
        target.activate()
        pasteTask = Task { @MainActor in
            // Wait for focus restoration and for the hotkey modifiers to be released.
            for _ in 0..<20 {
                try? await Task.sleep(for: .milliseconds(50))
                guard !Task.isCancelled, !target.isTerminated else { return }
                let flags = CGEventSource.flagsState(.combinedSessionState)
                let held = flags.intersection([.maskCommand, .maskControl, .maskAlternate, .maskShift])
                if NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier,
                   held.isEmpty {
                    guard let source = CGEventSource(stateID: .hidSystemState),
                          let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
                          let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else { return }
                    down.flags = .maskCommand
                    up.flags = .maskCommand
                    down.postToPid(target.processIdentifier)
                    up.postToPid(target.processIdentifier)
                    return
                }
            }
        }
    }

    private func makeFloatingWindow() -> NSPanel {
        if let floatingWindow { return floatingWindow }
        let panel = NSPanel(contentRect: NSRect(x: 0, y: 0, width: 440, height: 550),
                            styleMask: [.titled, .closable, .utilityWindow], backing: .buffered, defer: false)
        panel.title = "Histórico de Clipboard"
        panel.isReleasedWhenClosed = false
        panel.level = .floating
        panel.hidesOnDeactivate = false
        panel.collectionBehavior = [.moveToActiveSpace, .fullScreenAuxiliary]
        panel.contentViewController = makeContent()
        panel.setFrameAutosaveName("ClipboardHistoryFloatingWindow")
        floatingWindow = panel
        return panel
    }

    private func detach() {
        let origin = popover.contentViewController?.view.window?.frame.origin
        let panel = makeFloatingWindow()
        if popover.isShown, let origin { panel.setFrameOrigin(origin) }
        popover.performClose(nil)
        NSApp.activate(ignoringOtherApps: true)
        panel.makeKeyAndOrderFront(nil)
    }

    func popoverShouldDetach(_ popover: NSPopover) -> Bool { true }

    func detachableWindow(for popover: NSPopover) -> NSWindow? {
        makeFloatingWindow()
    }

    @objc func toggle() {
        rememberDestination(NSWorkspace.shared.frontmostApplication)
        if let floatingWindow, floatingWindow.isVisible {
            floatingWindow.orderOut(nil)
            return
        }
        if popover.isShown { popover.performClose(nil) }
        else if let button = status.button {
            NSApp.activate(ignoringOtherApps: true)
            popover.show(relativeTo: button.bounds, of: button, preferredEdge: .minY)
            popover.contentViewController?.view.window?.makeKey()
        }
    }
    func applicationWillTerminate(_ notification: Notification) {
        pasteTask?.cancel()
        if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
        if let hotkey { UnregisterEventHotKey(hotkey) }
        if let handler { RemoveEventHandler(handler) }
    }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.run()
